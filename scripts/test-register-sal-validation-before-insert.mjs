assert.ok(validation<insert,"Cumulative approved-amount validation must run before inserting SAL");
assert.match(fn,/const cumulativeAmount=current\.reduce\(\(s,x\)=>s\+Number\(x\.amount\|\|0\),0\)\+newAmount/);
